/**
 * Threshold eval: check that MIN_SIMILARITY still separates related from
 * unrelated questions. Chunks the demo documents and embeds them exactly as
 * the server does, then reports the top score of each unrelated question and
 * the best score of the expected document for each related one.
 * Runs offline: no database, no Groq calls.
 *
 * Usage: NODE_ENV=development node eval/threshold.js
 */
import { readFileSync, writeFileSync } from "fs";
import { buildDocumentChunks } from "../backend/rag/buildChunks.js";
import { embeddingText } from "../backend/rag/embeddingInput.js";
import { embed, EMBEDDING_MODEL } from "../backend/rag/embed.js";
import { cosineSimilarity } from "../backend/rag/similarity.js";
import { MIN_SIMILARITY } from "../backend/ai.js";

const RESULTS_FILE = new URL("./threshold-results.md", import.meta.url);

const readJson = (path) => JSON.parse(readFileSync(new URL(path, import.meta.url), "utf8"));
const documents = readJson("../backend/demo/sample-documents.json");
const related = readJson("./questions.json");
const unrelated = readJson("./unrelated-questions.json");

const chunks = [];
for (const doc of documents) {
  for (const c of buildDocumentChunks(doc)) {
    chunks.push({ title: doc.title, index: c.index, embedding: await embed(embeddingText(doc.title, c.text)) });
  }
}

async function rank(question) {
  const vector = await embed(question);
  return chunks
    .map((c) => ({ title: c.title, index: c.index, score: cosineSimilarity(vector, c.embedding) }))
    .sort((a, b) => b.score - a.score);
}

const fmt = (n) => n.toFixed(3);

const unrelatedRows = [];
for (const q of unrelated) {
  const [top] = await rank(q.question);
  unrelatedRows.push({ ...q, top });
}

const relatedRows = [];
for (const q of related) {
  const best = (await rank(q.question)).find((c) => c.title === q.expectedDoc);
  relatedRows.push({ ...q, best });
}

const maxUnrelated = unrelatedRows.reduce((a, b) => (b.top.score > a.top.score ? b : a));
const minRelated = relatedRows.reduce((a, b) => (b.best.score < a.best.score ? b : a));
const unrelatedPassing = unrelatedRows.filter((r) => r.top.score >= MIN_SIMILARITY);
const relatedFailing = relatedRows.filter((r) => r.best.score < MIN_SIMILARITY);

const summary = [
  `- Highest unrelated score: ${fmt(maxUnrelated.top.score)} (${maxUnrelated.id}, ${maxUnrelated.top.title} #${maxUnrelated.top.index})`,
  `- Unrelated questions at or above ${MIN_SIMILARITY}: ${unrelatedPassing.length} of ${unrelated.length}${unrelatedPassing.length ? ` (${unrelatedPassing.map((r) => r.id).join(", ")})` : ""}`,
  `- Lowest related score: ${fmt(minRelated.best.score)} (${minRelated.id}, ${minRelated.expectedDoc} #${minRelated.best.index})`,
  `- Related questions below ${MIN_SIMILARITY}: ${relatedFailing.length} of ${related.length}${relatedFailing.length ? ` (${relatedFailing.map((r) => r.id).join(", ")})` : ""}`,
].join("\n");

const unrelatedTable = [
  "| id | type | question | top score | top chunk |",
  "|---|---|---|---|---|",
  ...unrelatedRows.map((r) => `| ${r.id} | ${r.type} | ${r.question} | ${fmt(r.top.score)} | ${r.top.title} #${r.top.index} |`),
].join("\n");

const relatedTable = [
  "| id | question | expected document | best score | chunk |",
  "|---|---|---|---|---|",
  ...relatedRows.map((r) => `| ${r.id} | ${r.question} | ${r.expectedDoc} | ${fmt(r.best.score)} | #${r.best.index} |`),
].join("\n");

writeFileSync(RESULTS_FILE, `# Similarity threshold results

Generated by \`node eval/threshold.js\`. ${documents.length} demo documents chunked and embedded as in production, embedding model \`${EMBEDDING_MODEL}\`, MIN_SIMILARITY ${MIN_SIMILARITY}.

${summary}

## Unrelated questions (\`unrelated-questions.json\`)

The score of the best chunk in the whole corpus. It should stay below MIN_SIMILARITY.

${unrelatedTable}

## Related questions (\`questions.json\`)

The score of the best chunk of the expected document. It should reach MIN_SIMILARITY.

${relatedTable}
`);

console.log(`${summary}\n\nWritten to eval/threshold-results.md`);
